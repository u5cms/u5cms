class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self,*args,**kwargs):return None
class Browser:
    def __init__(self):
        self.cookies=http.cookiejar.CookieJar()
        self.opener=urllib.request.build_opener(urllib.request.ProxyHandler({}),NoRedirect(),urllib.request.HTTPCookieProcessor(self.cookies),
            urllib.request.HTTPSHandler(context=ssl.create_default_context(cafile=CA)))
    def request(self,url,form=None,headers=None):
        data=urlencode(form).encode() if form is not None else None
        request=urllib.request.Request(url,data=data,headers=headers or {})
        try:response=self.opener.open(request,timeout=25)
        except urllib.error.HTTPError as error:response=error
        with response:return response.status,response.headers,response.read()
def check(condition,label):
    global CHECKS
    if not condition:raise AssertionError(label)
    CHECKS+=1
